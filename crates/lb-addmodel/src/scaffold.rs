//! Turn a [`Probe`] into a `config.rs` an engineer can finish.
//!
//! Resolved fields are emitted with the key they came from. Defaulted fields are emitted with
//! the default and a comment saying the file did not state it. Missing fields are emitted as
//! `todo!()`, so the crate does not build until someone decides what belongs there.

use crate::probe::{MoeLayout, Origin, Probe};
use std::fmt::Write;

pub fn config_rs(p: &Probe) -> String {
    let mut s = String::new();
    let arch = &p.arch;
    let _ = writeln!(s, "//! `{arch}` hyperparameters, read from GGUF metadata.");
    let _ = writeln!(s, "//!");
    let _ = writeln!(s, "//! Generated by `lb-addmodel scaffold` from:");
    let _ = writeln!(s, "//!   {}", p.path);
    let _ = writeln!(s, "//! Review every `GENERATED:` comment before trusting this file.");
    let _ = writeln!(s, "\nuse anyhow::{{bail, Context, Result}};\nuse lb_gguf::Gguf;\n");
    let _ = writeln!(s, "#[derive(Clone, Debug)]\npub struct Config {{\n    pub arch: String,");
    for f in &p.fields {
        let _ = writeln!(s, "    /// {}", f.why);
        let _ = writeln!(s, "    pub {}: {},", f.name, f.ty);
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "impl Config {{\n    pub fn from_gguf(g: &Gguf) -> Result<Self> {{");
    let _ = writeln!(s, "        let arch = g.meta_str(\"general.architecture\").context(\"general.architecture\")?.to_string();");
    let _ = writeln!(s, "        if arch != \"{arch}\" {{\n            bail!(\"architecture {{arch}} is not {arch}\");\n        }}");
    let _ = writeln!(s, "        let k = |key: &str| -> Result<u64> {{ g.meta_u64(&format!(\"{{arch}}.{{key}}\")).with_context(|| format!(\"{{arch}}.{{key}}\")) }};");
    let _ = writeln!(s, "        let kf = |key: &str| -> Result<f64> {{ g.meta_f64(&format!(\"{{arch}}.{{key}}\")).with_context(|| format!(\"{{arch}}.{{key}}\")) }};");
    let _ = writeln!(s, "        Ok(Self {{");
    for f in &p.fields {
        let cast = match f.ty {
            "usize" => " as usize",
            "u32" => " as u32",
            "f32" => " as f32",
            _ => "",
        };
        match &f.origin {
            Origin::Key(key) => {
                let suffix = key.strip_prefix(&format!("{arch}.")).unwrap_or(key);
                let call = if f.ty == "f32" || f.ty == "f64" {
                    format!("kf(\"{suffix}\")?{cast}")
                } else if key.starts_with("tokenizer.") {
                    format!("g.meta_u64(\"{key}\").unwrap_or({}){cast}", f.value.clone().unwrap_or_default())
                } else if f.ty == "bool" {
                    format!("k(\"{suffix}\")? != 0")
                } else {
                    format!("k(\"{suffix}\")?{cast}")
                };
                let _ = writeln!(s, "            // from `{key}` = {}", f.value.clone().unwrap_or_default());
                let _ = writeln!(s, "            {}: {call},", f.name);
            }
            Origin::Default(d) => {
                let suffix = f.name;
                let _ = writeln!(s, "            // GENERATED: this file did not state it; engine default {d}");
                let key_suffix = match &f.origin { _ => suffix };
                let _ = writeln!(s, "            {}: {d},  // optional key absent in {key_suffix}", f.name);
            }
            Origin::Missing => {
                let _ = writeln!(s, "            // GENERATED: REQUIRED and absent from the file. Decide and remove the todo!().");
                let _ = writeln!(s, "            {}: todo!(\"{} ({})\"),", f.name, f.name, f.why);
            }
        }
    }
    let _ = writeln!(s, "            arch,\n        }})\n    }}\n");
    let _ = writeln!(s, "    pub fn head_dim(&self) -> usize {{\n        self.n_embd / self.n_head\n    }}");
    if p.moe_layout != MoeLayout::None {
        let _ = writeln!(s, "    pub fn is_moe(&self, layer: usize) -> bool {{\n        self.n_expert > 0 && layer >= self.n_dense_lead\n    }}");
    }
    let _ = writeln!(s, "}}");
    s
}
